def import_products(custom_db: Session = None):
    should_close = False
    if custom_db is None:
        db: Session = SessionLocal()
        should_close = True
    else:
        db = custom_db
    try:
        # 1. Ensure Brands Exist
        brands_to_ensure = [
            {
                "slug": "adeen",
                "name": "Adeen Hardware",
                "logo_url": "/brands/adeen.svg",
                "description_en": "Established architectural door accessories manufacturer renowned for kick-down stops, friction holders, and door hardware.",
                "description_ur": "معروف آرکیٹیکچرل ڈور فٹنگز اور کک ڈاؤن ڈور ہولڈرز کا قابل اعتماد برانڈ۔",
                "sort_order": 7,
            },
            {
                "slug": "ss-hardware",
                "name": "SS Architectural Hardware",
                "logo_url": "/brands/ss-hardware.svg",
                "description_en": "Premier architectural hardware, smart locks, luxury magnetic door stops, and designer sanitary fittings.",
                "description_ur": "پریمیم آرکیٹیکچرل ہارڈویئر، اسمارٹ لاکس، میگنیٹک ڈور اسٹاپر اور سینیٹری فٹنگز۔",
                "sort_order": 8,
            },
        ]

        brand_map = {}
        for b_data in brands_to_ensure:
            existing = db.query(Brand).filter(Brand.slug == b_data["slug"]).first()
            if not existing:
                b = Brand(**b_data)
                db.add(b)
                db.flush()
                brand_map[b.slug] = b
            else:
                brand_map[existing.slug] = existing

        # Load all brands into map
        for b in db.query(Brand).all():
            brand_map[b.slug] = b

        # 2. Category Map
        cat_map = {c.slug: c for c in db.query(Category).all()}

        imported_count = 0
        updated_count = 0

        for item in PRODUCTS_DATA:
            slug = item["slug"]
            cat_slug = item["category_slug"]
            subcat_slug = item["subcategory_slug"]
            brand_slug = item.get("brand_slug")

            cat = cat_map.get(cat_slug)
            subcat = cat_map.get(subcat_slug)
            brand = brand_map.get(brand_slug) if brand_slug else None

            existing_prod = db.query(Product).filter(Product.slug == slug).first()
            image_url = f"/images/products/{item['image_file']}"

            if not existing_prod:
                prod = Product(
                    id=uuid.uuid4(),
                    slug=slug,
                    sku=item["sku"],
                    name_en=item["name_en"],
                    name_ur=item["name_ur"],
                    short_description_en=item["short_description_en"],
                    short_description_ur=item["short_description_ur"],
                    description_en=item["description_en"],
                    description_ur=item["description_ur"],
                    price=None,
                    price_on_request=True,
                    is_published=True,
                    is_featured=item.get("is_featured", False),
                    is_best_seller=item.get("is_best_seller", False),
                    brand_id=brand.id if brand else None,
                    stock_status=StockStatus.IN_STOCK,
                    specifications=item.get("specifications"),
                    meta_title_en=f"{item['name_en']} | Naseer Hardware Sargodha",
                    meta_title_ur=f"{item['name_ur']} | نصیر ہارڈویئر سرگودھا",
                    meta_description_en=item["short_description_en"],
                    meta_description_ur=item["short_description_ur"],
                )
                db.add(prod)
                db.flush()

                # Add category relations
                if cat:
                    db.execute(
                        text("INSERT INTO product_categories (product_id, category_id) VALUES (:pid, :cid) ON CONFLICT DO NOTHING"),
                        {"pid": prod.id, "cid": cat.id},
                    )
                if subcat and subcat.id != getattr(cat, "id", None):
                    db.execute(
                        text("INSERT INTO product_categories (product_id, category_id) VALUES (:pid, :cid) ON CONFLICT DO NOTHING"),
                        {"pid": prod.id, "cid": subcat.id},
                    )

                # Add primary image
                img = ProductImage(
                    id=uuid.uuid4(),
                    product_id=prod.id,
                    image_url=image_url,
                    alt_text_en=item["alt_en"],
                    alt_text_ur=item["alt_ur"],
                    sort_order=1,
                    is_primary=True,
                )
                db.add(img)
                imported_count += 1
            else:
                # Update existing product
                existing_prod.sku = item["sku"]
                existing_prod.name_en = item["name_en"]
                existing_prod.name_ur = item["name_ur"]
                existing_prod.short_description_en = item["short_description_en"]
                existing_prod.short_description_ur = item["short_description_ur"]
                existing_prod.description_en = item["description_en"]
                existing_prod.description_ur = item["description_ur"]
                existing_prod.specifications = item.get("specifications")
                existing_prod.price = None
                existing_prod.price_on_request = True
                existing_prod.is_published = True
                existing_prod.is_featured = item.get("is_featured", False)
                existing_prod.is_best_seller = item.get("is_best_seller", False)
                if brand:
                    existing_prod.brand_id = brand.id

                # Ensure image
                img_exists = db.query(ProductImage).filter(
                    ProductImage.product_id == existing_prod.id,
                    ProductImage.image_url == image_url,
                ).first()
                if not img_exists:
                    img = ProductImage(
                        id=uuid.uuid4(),
                        product_id=existing_prod.id,
                        image_url=image_url,
                        alt_text_en=item["alt_en"],
                        alt_text_ur=item["alt_ur"],
                        sort_order=1,
                        is_primary=True,
                    )
                    db.add(img)

                # Ensure categories
                if cat:
                    db.execute(
                        text("INSERT INTO product_categories (product_id, category_id) VALUES (:pid, :cid) ON CONFLICT DO NOTHING"),
                        {"pid": existing_prod.id, "cid": cat.id},
                    )
                if subcat and subcat.id != getattr(cat, "id", None):
                    db.execute(
                        text("INSERT INTO product_categories (product_id, category_id) VALUES (:pid, :cid) ON CONFLICT DO NOTHING"),
                        {"pid": existing_prod.id, "cid": subcat.id},
                    )
                updated_count += 1

        db.commit()
        print(f"Successfully processed {len(PRODUCTS_DATA)} products! (Imported: {imported_count}, Updated: {updated_count})")
    except Exception as e:
        db.rollback()
        print(f"Error during import: {e}")
        raise
    finally:
        if should_close:
            db.close()

if __name__ == "__main__":
    import_products()
